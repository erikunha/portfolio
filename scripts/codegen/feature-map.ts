function countUnder(files: readonly string[], prefix: string): number {
  return files.filter((file) => file.startsWith(prefix)).length;
}

function renderFeature(feature: Feature, files: readonly string[]): string {
  const rows = feature.prefixes.map((prefix) => `| \`${prefix}\` | ${countUnder(files, prefix)} |`);
  return [
    `## ${feature.name}`,
    '',
    feature.purpose,
    '',
    '| Path prefix | Tracked files |',
    '| --- | ---: |',
    ...rows,
  ].join(LINE_BREAK);
}

export function renderFeatureMap(files: string[]): string {
  const header = [
    '# Feature map',
    '',
    `Generated by \`${COMMAND}\` from the tracked files. Do not edit by hand.`,
  ].join(LINE_BREAK);
  const sections = FEATURES.map((feature) => renderFeature(feature, files));
  return `${[header, ...sections].join(`${LINE_BREAK}${LINE_BREAK}`)}${LINE_BREAK}`;
}

if (isMain(import.meta.url)) {
  writeFileSync(MAP_PATH, renderFeatureMap(trackedFiles([], { cwd: ROOT })));
}
