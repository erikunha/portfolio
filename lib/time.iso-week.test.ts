import { describe, expect, it } from 'vitest';
import { isoWeek } from '@/lib/time';

describe('isoWeek', () => {
  it.each([
    ['2026-11-24T10:00:00Z', '2026-W48'],
    ['2026-11-23T00:00:00Z', '2026-W48'],
    ['2026-11-29T23:59:59Z', '2026-W48'],
    ['2026-11-30T00:00:00Z', '2026-W49'],
    ['2021-01-03T12:00:00Z', '2020-W53'],
    ['2021-01-04T00:00:00Z', '2021-W01'],
    ['2024-12-30T12:00:00Z', '2025-W01'],
    ['2026-01-01T00:00:00Z', '2026-W01'],
    ['2027-01-01T00:00:00Z', '2026-W53'],
  ])('%s is %s', (iso, week) => {
    expect(isoWeek(new Date(iso))).toBe(week);
  });
});
