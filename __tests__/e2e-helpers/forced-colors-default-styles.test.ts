const DECORATIVE_STYLES_SNAPSHOT: Record<string, Record<string, string>> = {
  '[data-testid^="crt-"]': {
    display: 'block',
    visibility: 'visible',
  },
  'canvas[aria-hidden]': {
    display: 'block',
    visibility: 'visible',
  },
};

describe('forced-colors default styles', () => {
  it('builds the control table with the same selectors, properties, values and order', () => {
    expect(Object.keys(DEFAULT_CONTROL_STYLES)).toEqual(Object.keys(CONTROL_STYLES_SNAPSHOT));
    for (const [selector, styles] of Object.entries(CONTROL_STYLES_SNAPSHOT)) {
      expect(Object.entries(DEFAULT_CONTROL_STYLES[selector] ?? {}), selector).toEqual(
        Object.entries(styles),
      );
    }
  });

  it('keeps the decorative table unchanged', () => {
    expect(DEFAULT_DECORATIVE_STYLES).toEqual(DECORATIVE_STYLES_SNAPSHOT);
  });
});
