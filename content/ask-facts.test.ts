import { describe, expect, it } from 'vitest';
import { askFacts } from './ask-facts';
import { communityEvent } from './community';
import { designSystemTake, homeTakes } from './hottest-takes';
import { RAYLU_BUILT_CLAIM } from './profile';
import { projects } from './projects';
import { SITE_LOCALE } from './site-locale';

const LEDGERLENS = projects[SITE_LOCALE.en].find((project) => project.name === 'LEDGERLENS');
const ESTIMATE_STORY = askFacts.stories.find((story) => story.title.startsWith('Re-anchoring'));
const NAMED_PARTY = /colleague|coworker|accus|AI-produced|AI-generated|generated by AI/i;

describe('ask facts', () => {
  it('states every published take as an opinion, from the module the page renders', () => {
    const takes = [...homeTakes(SITE_LOCALE.en), designSystemTake(SITE_LOCALE.en)];
    for (const take of takes) {
      expect(askFacts.opinions, take?.thesis).toContain(take?.thesis);
    }
  });

  it('states the community role from the community module with the talk count it publishes', () => {
    const [talks] = communityEvent[SITE_LOCALE.en].bullets;
    const line = askFacts.community.join(' ');
    expect(line, 'the ask facts must carry the talks the community module publishes').toContain(
      (talks ?? '').replace(/\.$/, ''),
    );
    expect(line).toContain('8 talks');
  });

  it('states the Raylu build claim the CV states, and no sole ownership', () => {
    expect(askFacts.currentRoleScope.join(' ')).toContain(RAYLU_BUILT_CLAIM);
    expect(askFacts.currentRoleScope.join(' ')).toContain('He never claims sole ownership');
  });

  it('tells the estimate story without naming or accusing anyone', () => {
    expect(ESTIMATE_STORY, 'the approved estimate story is missing').toBeDefined();
    expect(ESTIMATE_STORY?.text).toContain('14 comparable migrations');
    expect(ESTIMATE_STORY?.text).toContain('3 to 4 weeks');
    expect(
      ESTIMATE_STORY?.text,
      'the story is approved only anonymized: no colleague and no accusation wording',
    ).not.toMatch(NAMED_PARTY);
  });

  it('attaches the caveat to every Raylu repository figure it publishes', () => {
    const detail = askFacts.currentRoleDetail.join(' ');
    expect(detail).toContain('git blame credits surviving lines');
    expect(detail).toContain('two different component sets in a dev build');
    expect(detail).toContain('component facts, not product claims');
  });

  it('states the LedgerLens trajectory miss and its sample-size limit where the model reads them', () => {
    expect(LEDGERLENS, 'LedgerLens is missing from the projects').toBeDefined();
    expect(LEDGERLENS?.url).toBe('https://github.com/erikunha/ledgerlens');
    expect(LEDGERLENS?.description).toContain('0.73 against a 0.80 target');
    expect(LEDGERLENS?.description).toContain('a trend, not significance');
    const detail = askFacts.projectDetail.join(' ');
    expect(detail).toContain('a miss');
    expect(detail).toContain('a trend, not statistical significance');
    expect(detail).toContain('not a production service');
  });

  it('keeps the employment list closed so an employer outside it is not invented', () => {
    expect(askFacts.calibration.join(' ')).toContain('The employment history is complete');
  });
});
