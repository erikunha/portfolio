#!/usr/bin/env tsx
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isMain } from '../lib/is-main';

const ROOT = join(import.meta.dirname, '../..');
const DECISIONS_PATH = join(ROOT, 'DECISIONS.md');
const COMMAND = 'pnpm decisions:index';
const CHECK_FLAG = '--check';
const LINE_BREAK = '\n';
const FAILURE_EXIT_CODE = 1;
const MAX_TITLE_LENGTH = 110;
const MAX_REVERSIBILITY_LENGTH = 70;
const ELLIPSIS = '...';
const DEFAULT_AREA = 'general';
const UNSTATED = 'unstated';

export const INDEX_START = '<!-- decisions-index:start -->';
export const INDEX_END = '<!-- decisions-index:end -->';

const ENTRY_START = /^- \*\*(\d{4}-\d{2}-\d{2})\*\*(?:\s*[·:-]\s*|\s+)/;
const HEADING = /^## (.*)$/;
const HEADING_DATE_PREFIX = /^\d{4}-\d{2}-\d{2}[:,]\s*/;
const BOLD_LEAD = /^\*\*(.+?)\*\*/;
const SENTENCE_END = /[.!?](?:\s|$)/;
const TRAILING_PERIOD = /\.$/;
const SUPERSEDED_MARKER_OPEN = /(?<![`\p{L}\p{N}])Superseded/u.source;
const PARTLY_SUPERSEDED = new RegExp(`${SUPERSEDED_MARKER_OPEN} in part`, 'u');
const SUPERSEDED = new RegExp(
  `${SUPERSEDED_MARKER_OPEN}(?: \\(| \\d{4}-| by | the same day| below|:)`,
  'u',
);
const REVERSIBLE_NOTE = '_Reversib';
const NOTE_DELIMITER = /^Reversib[a-z ()]*?[:.;,]\s*/;
const CLAUSE_END = /;|\.(?:\s|$)/;
const TRAILING_UNDERSCORES = /_+\s*$/;
const INTRO_END = /^[^#\n][^\n]*\n\n(?=- )/m;

export type DecisionStatus = 'active' | 'superseded' | 'partly superseded';

export interface DecisionEntry {
  date: string;
  area: string;
  title: string;
  status: DecisionStatus;
  reversibility: string;
}

function truncate(text: string, limit: number): string {
  if (text.length <= limit) return text;
  return `${text.slice(0, limit - ELLIPSIS.length).trimEnd()}${ELLIPSIS}`;
}

function stripIndex(markdown: string): string {
  const start = markdown.indexOf(INDEX_START);
  const end = markdown.indexOf(INDEX_END);
  if (start === -1 || end === -1 || end < start) return markdown;
  return markdown.slice(0, start) + markdown.slice(end + INDEX_END.length);
}

function titleOf(text: string): string {
  const bold = BOLD_LEAD.exec(text);
  const raw = bold?.[1] ?? text.slice(0, text.search(SENTENCE_END) + 1 || text.length);
  return truncate(raw.trim().replace(TRAILING_PERIOD, ''), MAX_TITLE_LENGTH);
}

function statusOf(text: string): DecisionStatus {
  if (PARTLY_SUPERSEDED.test(text)) return 'partly superseded';
  return SUPERSEDED.test(text) ? 'superseded' : 'active';
}

function reversibilityOf(text: string): string {
  const at = text.lastIndexOf(REVERSIBLE_NOTE);
  if (at === -1) return UNSTATED;
  const note = text
    .slice(at + 1)
    .replace(TRAILING_UNDERSCORES, '')
    .replace(NOTE_DELIMITER, '');
  const clauseEnd = note.search(CLAUSE_END);
  const clause = clauseEnd === -1 ? note : note.slice(0, clauseEnd);
  return truncate(clause.trim() || UNSTATED, MAX_REVERSIBILITY_LENGTH);
}

export function parseDecisions(markdown: string): DecisionEntry[] {
  const entries: DecisionEntry[] = [];
  let area = DEFAULT_AREA;
  let pending: { date: string; lines: string[]; area: string } | undefined;
  const flush = () => {
    if (pending === undefined) return;
    const text = pending.lines.join(' ').trim();
    entries.push({
      date: pending.date,
      area: pending.area,
      title: titleOf(text),
      status: statusOf(text),
      reversibility: reversibilityOf(text),
    });
    pending = undefined;
  };
  for (const line of stripIndex(markdown).split(LINE_BREAK)) {
    const heading = HEADING.exec(line);
    const start = ENTRY_START.exec(line);
    if (heading !== null) {
      flush();
      area = (heading[1] ?? '').replace(HEADING_DATE_PREFIX, '').trim() || DEFAULT_AREA;
    } else if (start !== null) {
      flush();
      pending = { date: start[1] ?? '', lines: [line.slice(start[0].length)], area };
    } else if (pending !== undefined) {
      pending.lines.push(line.trim());
    }
  }
  flush();
  return entries;
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|');
}

export function renderIndex(entries: readonly DecisionEntry[]): string {
  const rows = entries.map(
    (entry) =>
      `| ${entry.date} | ${cell(entry.area)} | ${cell(entry.title)} | ${entry.status} | ${cell(entry.reversibility)} |`,
  );
  return [
    INDEX_START,
    `Index of every dated bullet below. Generated by \`${COMMAND}\`; do not edit by hand.`,
    '',
    '| Date | Area | Decision | Status | Reversible |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    INDEX_END,
    '',
  ].join(LINE_BREAK);
}

export function applyIndex(markdown: string): string {
  const entries = parseDecisions(markdown);
  const block = renderIndex(entries);
  const start = markdown.indexOf(INDEX_START);
  const end = markdown.indexOf(INDEX_END);
  if (start !== -1 && end > start) {
    return markdown.slice(0, start) + block + markdown.slice(end + INDEX_END.length + 1);
  }
  const intro = INTRO_END.exec(markdown);
  const at = intro === null ? markdown.length : intro.index + intro[0].length;
  return `${markdown.slice(0, at)}${block}${LINE_BREAK}${markdown.slice(at)}`;
}

if (isMain(import.meta.url)) {
  const current = readFileSync(DECISIONS_PATH, 'utf8');
  const next = applyIndex(current);
  if (process.argv.includes(CHECK_FLAG)) {
    if (next !== current) {
      console.error(`DECISIONS.md index is stale: run \`${COMMAND}\` and commit DECISIONS.md`);
      process.exit(FAILURE_EXIT_CODE);
    }
  } else {
    writeFileSync(DECISIONS_PATH, next);
  }
}
